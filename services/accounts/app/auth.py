@router.post(
    "/register",
    status_code=201,
    dependencies=[Depends(csrf_guard)],
)
def register(body: Credentials, response: Response, request: Request):
    rate_limit(request, body.username)

    try:
        with get_connection() as db:
            cur = db.cursor()

            cur.execute(
                """
                INSERT INTO users (username, password_hash)
                VALUES (%s, %s)
                RETURNING id
                """,
                (
                    body.username.lower(),
                    hash_password(body.password),
                ),
            )

            user_id = cur.fetchone()["id"]
            db.commit()

    except UniqueViolation as exc:
        raise HTTPException(
            status_code=409,
            detail="Этот логин уже занят",
        ) from exc

    create_session(user_id, response, request)

    return {
        "id": user_id,
        "username": body.username.lower(),
        "team_id": "fukurodani",
        "avatar_url": None,
    }


@router.post('/login', dependencies=[Depends(csrf_guard)])
def login(body: Credentials, response: Response, request: Request):
    rate_limit(request, body.username)
    with get_connection() as db:
        cur = db.cursor()
        cur.execute('SELECT * FROM users WHERE username=%s', (body.username.lower(),))
        user = cur.fetchone()
    encoded = user['password_hash'] if user else f'scrypt${b"fixed-dummy-salt".hex()}${DUMMY_HASH}'
    valid = verify_password(body.password, encoded)
    if not user or not valid:
        raise HTTPException(401, 'Неверный логин или пароль')
    create_session(user['id'], response, request)
    return public_user(user)


