def hash_password(password):
    salt = secrets.token_hex(16)
    digest = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=1).hex()
    return f'scrypt${salt}${digest}'


def verify_password(password, encoded):
    try:
        _, salt, expected = encoded.split('$')
        actual = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=1).hex()
        return hmac.compare_digest(actual, expected)
    except (ValueError, TypeError):
        return False


def csrf_guard(x_requested_with: str = Header("")):
    if x_requested_with != 'VolnaApp':
        raise HTTPException(403, 'Обновите страницу и повторите запрос')


def rate_limit(request, username):
    key = ((request.client.host if request.client else 'unknown'), username.lower())
    now = time.monotonic()
    with _attempt_lock:
        for stale in list(_attempts):
            _attempts[stale] = [t for t in _attempts[stale] if now-t < 60]
            if not _attempts[stale]:
                del _attempts[stale]
        entries = _attempts[key]
        if len(entries) >= 10:
            raise HTTPException(429, 'Слишком много попыток. Подождите минуту')
        entries.append(now)


def public_user(row):
    return {'id': row['id'], 'username': row['username'], 'team_id': row['team_id'],
            'avatar_url': f"/api/photos/avatars/{row['avatar']}" if row.get('avatar') else None}


def current_user(request: Request):
    token = request.cookies.get('volna_session', '')
    if not token or len(token) > 128:
        raise HTTPException(401, 'Войдите в аккаунт')
    with get_connection() as db:
        cur = db.cursor()
        cur.execute(
            """
            SELECT u.*
            FROM users u
            JOIN user_sessions s ON u.id = s.user_id
            WHERE s.token_hash = %s
              AND s.expires_at > CURRENT_TIMESTAMP
            """,
            (hashlib.sha256(token.encode()).hexdigest(),),
        )
        user = cur.fetchone()
    if not user:
        raise HTTPException(401, 'Сессия истекла. Войдите снова')
    return user


def create_session(user_id, response, request):
    token = secrets.token_urlsafe(32)
    with get_connection() as db:
        cur = db.cursor()
        old = request.cookies.get('volna_session', '')
        if old:
            cur.execute('DELETE FROM user_sessions WHERE token_hash=%s', (hashlib.sha256(old.encode()).hexdigest(),))
        cur.execute('INSERT INTO user_sessions (token_hash,user_id,expires_at) VALUES (%s,%s,%s)',
                    (hashlib.sha256(token.encode()).hexdigest(), user_id,
                     datetime.now(timezone.utc) + timedelta(seconds=SESSION_SECONDS)))
        db.commit()
    response.set_cookie('volna_session', token, max_age=SESSION_SECONDS, httponly=True,
                        secure=os.getenv('COOKIE_SECURE', 'false').lower() == 'true', samesite='lax', path='/')
    response.headers['Cache-Control'] = 'no-store'


class Credentials(BaseModel):
    username: str = Field(min_length=3, max_length=40, pattern=r'^[A-Za-z0-9_]+$')
    password: str = Field(min_length=8, max_length=128)


class Preferences(BaseModel):
    team_id: str


