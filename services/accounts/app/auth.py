@router.post('/logout', status_code=204, dependencies=[Depends(csrf_guard)])
def logout(request: Request, response: Response):
    token = request.cookies.get('volna_session', '')
    with get_connection() as db:
        cur = db.cursor()
        cur.execute('DELETE FROM user_sessions WHERE token_hash=%s', (hashlib.sha256(token.encode()).hexdigest(),))
        db.commit()
    response.delete_cookie('volna_session', path='/')


@router.patch('/profile', dependencies=[Depends(csrf_guard)])
def preferences(body: Preferences, user=Depends(current_user)):
    if body.team_id not in {t['id'] for t in TEAMS}:
        raise HTTPException(422, 'Выберите команду из списка')
    with get_connection() as db:
        cur = db.cursor()
        cur.execute('UPDATE users SET team_id=%s WHERE id=%s', (body.team_id, user['id']))
        db.commit()
    user['team_id'] = body.team_id
    return public_user(user)


@router.post('/avatar', dependencies=[Depends(csrf_guard)])
async def avatar(photo: UploadFile = File(...), user=Depends(current_user)):
    data = await photo.read(5*1024*1024+1)
    await photo.close()
    if len(data) > 5*1024*1024:
        raise HTTPException(413, 'Размер аватарки — до 5 МБ')
    try:
        with Image.open(io.BytesIO(data)) as original:
            if original.format not in {'JPEG', 'PNG', 'WEBP'}:
                raise ValueError()
            image = ImageOps.fit(ImageOps.exif_transpose(original).convert('RGB'), (512, 512))
            output = io.BytesIO()
            image.save(output, 'JPEG', quality=90)
    except (ValueError, OSError, UnidentifiedImageError, Image.DecompressionBombError):
        raise HTTPException(422, 'Выберите изображение JPG, PNG или WebP')
    filename = f'{user["id"]}-{uuid4().hex}.jpg'
    path = AVATARS / filename
    try:
        path.write_bytes(output.getvalue())
        with get_connection() as db:
            cur = db.cursor()
            cur.execute('UPDATE users SET avatar=%s WHERE id=%s', (filename, user['id']))
            db.commit()
    except Exception:
        path.unlink(missing_ok=True)
        raise
    user['avatar'] = filename
    return public_user(user)
