-- PostgreSQL schema. Safe to run on both a new and an existing database.
-- Accounts and sessions are initialized separately by app.auth.
CREATE TABLE IF NOT EXISTS team (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    city VARCHAR(120) NOT NULL,
    founded_year INTEGER NOT NULL,
    arena VARCHAR(160) NOT NULL,
    coach VARCHAR(120) NOT NULL,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS players (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number INTEGER NOT NULL UNIQUE CHECK (number BETWEEN 1 AND 99),
    full_name VARCHAR(120) NOT NULL,
    position VARCHAR(80) NOT NULL,
    height_cm INTEGER NOT NULL CHECK (height_cm BETWEEN 150 AND 230),
    country VARCHAR(80) NOT NULL,
    photo_filename VARCHAR(100)
);

